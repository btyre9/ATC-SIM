"""Builds runways-data.js from the FAA's public Runways dataset (Aeronautical Information Services).

Each FAA runway is a pavement outline. The runway ends are the midpoints of its two short sides;
each end is matched to its designator by comparing the runway number with the true bearing.
Run from the project folder:  python3 tools/build_runways.py
To rebuild only some airports and keep the rest:  python3 tools/build_runways.py KDTW
"""
import json
import math
import re
import sys
import urllib.parse
import urllib.request

SERVICE = ('https://services6.arcgis.com/ssFJjBXIUyZDrSYZ/arcgis/rest/services/'
           'Runways/FeatureServer/0/query')
SECTORS = {
    'KATL': (33.6407, -84.4277),
    'KSAN': (32.7336, -117.1897),
    'KCLT': (35.2140, -80.9431),
    'KDTW': (42.2124, -83.3534),
}
SEARCH_NM = 3


def fetch(lat, lon):
    span_lat = SEARCH_NM / 60
    span_lon = SEARCH_NM / (60 * math.cos(math.radians(lat)))
    query = urllib.parse.urlencode({
        'where': '1=1', 'geometryType': 'esriGeometryEnvelope', 'inSR': 4326, 'outSR': 4326,
        'geometry': f'{lon - span_lon},{lat - span_lat},{lon + span_lon},{lat + span_lat}',
        'outFields': 'DESIGNATOR,LENGTH,WIDTH,AIRPORT_ID', 'f': 'json'})
    with urllib.request.urlopen(f'{SERVICE}?{query}', timeout=30) as response:
        data = json.load(response)
    if 'error' in data:
        raise SystemExit(f"FAA service error: {data['error']}")
    return data['features']


def bearing(a, b):
    lat1, lat2 = math.radians(a[1]), math.radians(b[1])
    dlon = math.radians(b[0] - a[0])
    y = math.sin(dlon) * math.cos(lat2)
    x = math.cos(lat1) * math.sin(lat2) - math.sin(lat1) * math.cos(lat2) * math.cos(dlon)
    return (math.degrees(math.atan2(y, x)) + 360) % 360


def distance_ft(a, b):
    east = (b[0] - a[0]) * 60 * math.cos(math.radians(a[1]))
    north = (b[1] - a[1]) * 60
    return math.hypot(east, north) * 6076.12


def angle_between(a, b):
    return abs((a - b + 180) % 360 - 180)


def runway(feature):
    designator = feature['attributes']['DESIGNATOR']
    idents = designator.split('/')
    if len(idents) != 2 or not all(re.match(r'^\d{1,2}[LCR]?$', ident) for ident in idents):
        return None  # Helipads and water lanes.
    ring = feature['geometry']['rings'][0][:-1]
    if len(ring) != 4:
        return None
    # The short sides of the outline are the runway ends.
    sides = [(ring[i], ring[(i + 1) % 4]) for i in range(4)]
    sides.sort(key=lambda side: distance_ft(*side))
    ends = [((a[0] + b[0]) / 2, (a[1] + b[1]) / 2) for a, b in sides[:2]]
    course = bearing(ends[0], ends[1])
    # Runway 08 points roughly east: land at the end whose number matches the course toward the other end.
    number = int(re.match(r'\d+', idents[0]).group()) * 10
    if angle_between(number, course) > 90:
        ends.reverse()
        course = bearing(ends[0], ends[1])
    return {
        'name': idents[0], 'recip': idents[1],
        'lat1': round(ends[0][1], 6), 'lon1': round(ends[0][0], 6),
        'lat2': round(ends[1][1], 6), 'lon2': round(ends[1][0], 6),
        'heading': round(course, 1),
        'lengthFt': feature['attributes']['LENGTH'], 'widthFt': feature['attributes']['WIDTH'],
    }


def own_runways(features, lat, lon):
    """Keeps runways of the airport nearest the reference point, dropping neighbours such as North Island."""
    def centre_distance(feature):
        ring = feature['geometry']['rings'][0]
        cx, cy = sum(p[0] for p in ring) / len(ring), sum(p[1] for p in ring) / len(ring)
        return distance_ft((lon, lat), (cx, cy))
    nearest = min(features, key=centre_distance)['attributes']['AIRPORT_ID']
    return [f for f in features if f['attributes']['AIRPORT_ID'] == nearest]


def load_existing():
    with open('runways-data.js') as source:
        return json.loads(source.read().split('=', 1)[1].strip().rstrip(';'))


def main():
    only = set(sys.argv[1:])
    data = load_existing() if only else {}
    for sector, position in SECTORS.items():
        if only and sector not in only:
            continue
        runways = [r for r in (runway(f) for f in own_runways(fetch(*position), *position)) if r]
        data[sector] = sorted(runways, key=lambda r: r['name'])
        print(sector, [(r['name'], r['recip'], r['heading'], r['lengthFt']) for r in data[sector]])
    with open('runways-data.js', 'w') as out:
        out.write('/* Generated by tools/build_runways.py from FAA Runways (public domain). Do not edit by hand. */\n')
        out.write(f'window.ATC_RUNWAYS = {json.dumps(data, indent=1)};\n')


if __name__ == '__main__':
    main()
